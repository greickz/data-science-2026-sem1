# Entre com um número e utilize operadores de atribuição para realizar as seguintes
# operações, imprimindo o resultado a cada etapa:
# a) Adicione 5 ao número
# b) Multiplique o valor por 2
# c) Subtraia 3
# d) Divida por 2
# e) Tire o resto da divisão por 3

num = float(input("Digite um número: "))
num += 5
print(f"a) Após adicionar 5: {num}")
num *= 2
print(f"b) Após multiplicar por 2: {num}")
num -= 3
print(f"c) Após subtrair 3: {num}")
num /= 2
print(f"d) Após dividir por 2: {num}")
num %= 3
print(f"e) Após tirar o resto da divisão por 3: {num}")